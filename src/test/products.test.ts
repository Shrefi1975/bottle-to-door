import { describe, expect, it } from "vitest";
import { BRANDS } from "@/lib/products";

describe("Supplied product prices in SAR", () => {
  it.each([
    ["البيان", "330 مل — 40 حبة", 11],
    ["طويق", "330 مل — 40 حبة", 10],
    ["طويق", "330 مل شرنك — 24 حبة", 5],
    ["أصايل", "200 مل — 48 حبة", 11],
    ["أصايل", "330 مل — 40 حبة", 10],
    ["أصايل", "330 مل شرنك", 5],
    ["ميراد", "200 مل — 48 حبة", 11],
    ["ميراد", "330 مل — 40 حبة", 10],
    ["ميراد", "330 مل شرنك", 6],
    ["ميراد", "600 مل", 12],
    ["ميراد", "5 لتر", 10],
    ["صفا", "200 مل — 48 حبة", 20],
    ["صفا", "330 مل — 40 حبة", 19],
    ["صفا", "1.5 لتر", 15],
    ["صفا", "جالون 5 لتر", 15],
    ["أكويا", "200 مل — 48 حبة", 14],
    ["أكويا", "330 مل — 40 حبة", 15],
    ["رفا", "250 مل — 40 حبة", 12],
    ["رفا", "330 مل — 40 حبة", 12],
    ["العين", "330 مل — 40 حبة", 12],
  ])("%s %s costs %i", (brand, label, price) => {
    expect(BRANDS[brand]?.find((pack) => pack.label === label)?.price).toBe(price);
  });

  it("does not offer Safa 600 ml without a supplied price", () => {
    expect(BRANDS["صفا"]?.some((pack) => pack.label.includes("600"))).toBe(false);
  });
});